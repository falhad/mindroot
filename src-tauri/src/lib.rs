//! Branchmint backend.
//!
//! Each mind map is one JSON file in `<app-data>/maps/<id>.json`. The file holds a
//! top-level `meta` object (title, timestamps, counts) so the dashboard can list maps
//! without parsing every node. Writes are atomic (temp file + rename) so a crash
//! mid-save never corrupts a map.

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use serde_json::Value;
use tauri::ipc::{InvokeBody, Request};
use tauri::{AppHandle, Manager};

type CmdResult<T> = Result<T, String>;

fn maps_dir(app: &AppHandle) -> CmdResult<PathBuf> {
    let dir = app
        .path()
        .app_data_dir()
        .map_err(|e| e.to_string())?
        .join("maps");
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir)
}

/// Map ids are generated by the frontend. Accept only a safe charset so an id can never
/// escape the maps directory.
fn validate_id(id: &str) -> CmdResult<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if ok {
        Ok(())
    } else {
        Err(format!("invalid map id: {id:?}"))
    }
}

fn map_path(app: &AppHandle, id: &str) -> CmdResult<PathBuf> {
    validate_id(id)?;
    Ok(maps_dir(app)?.join(format!("{id}.json")))
}

fn atomic_write(path: &Path, bytes: &[u8]) -> CmdResult<()> {
    let tmp = path.with_extension("tmp");
    {
        let mut f = fs::File::create(&tmp).map_err(|e| e.to_string())?;
        f.write_all(bytes).map_err(|e| e.to_string())?;
        f.sync_all().map_err(|e| e.to_string())?;
    }
    fs::rename(&tmp, path).map_err(|e| e.to_string())
}

/// `meta` object of every map file in `dir`. Unreadable or corrupt files are skipped, not fatal.
fn read_metas(dir: &Path) -> CmdResult<Vec<Value>> {
    let mut out = Vec::new();
    for entry in fs::read_dir(dir).map_err(|e| e.to_string())?.flatten() {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let Ok(text) = fs::read_to_string(&path) else { continue };
        let Ok(mut doc) = serde_json::from_str::<Value>(&text) else { continue };
        if let Some(meta) = doc.get_mut("meta").map(Value::take) {
            out.push(meta);
        }
    }
    Ok(out)
}

fn write_map(dir: &Path, id: &str, json: &str) -> CmdResult<()> {
    validate_id(id)?;
    serde_json::from_str::<Value>(json).map_err(|e| format!("refusing to save invalid JSON: {e}"))?;
    atomic_write(&dir.join(format!("{id}.json")), json.as_bytes())
}

#[tauri::command]
fn list_maps(app: AppHandle) -> CmdResult<Vec<Value>> {
    read_metas(&maps_dir(&app)?)
}

#[tauri::command]
fn load_map(app: AppHandle, id: String) -> CmdResult<Option<String>> {
    let path = map_path(&app, &id)?;
    if !path.exists() {
        return Ok(None);
    }
    fs::read_to_string(path)
        .map(Some)
        .map_err(|e| e.to_string())
}

#[tauri::command]
fn save_map(app: AppHandle, id: String, json: String) -> CmdResult<()> {
    write_map(&maps_dir(&app)?, &id, &json)
}

#[tauri::command]
fn delete_map(app: AppHandle, id: String) -> CmdResult<()> {
    let path = map_path(&app, &id)?;
    if path.exists() {
        fs::remove_file(path).map_err(|e| e.to_string())?;
    }
    Ok(())
}

/// Writes raw bytes (PNG/PDF/…) to a path the user picked in the save dialog.
/// The path travels in the `path` header (URI-encoded); the body is the raw payload,
/// which avoids serialising big binaries as JSON number arrays.
#[tauri::command]
fn save_bytes(request: Request<'_>) -> CmdResult<()> {
    let InvokeBody::Raw(bytes) = request.body() else {
        return Err("expected a raw body".into());
    };
    let encoded = request
        .headers()
        .get("path")
        .and_then(|v| v.to_str().ok())
        .ok_or("missing path header")?;
    let path = percent_decode(encoded)?;
    atomic_write(Path::new(&path), bytes)
}

fn percent_decode(s: &str) -> CmdResult<String> {
    let b = s.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            let hex = std::str::from_utf8(&b[i + 1..i + 3]).map_err(|e| e.to_string())?;
            out.push(u8::from_str_radix(hex, 16).map_err(|e| e.to_string())?);
            i += 3;
        } else {
            out.push(b[i]);
            i += 1;
        }
    }
    String::from_utf8(out).map_err(|e| e.to_string())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(tauri::generate_handler![
            list_maps, load_map, save_map, delete_map, save_bytes
        ])
        .run(tauri::generate_context!())
        .expect("error while running Branchmint");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_are_validated() {
        assert!(validate_id("abc-123_X").is_ok());
        assert!(validate_id("../etc/passwd").is_err());
        assert!(validate_id("").is_err());
        assert!(validate_id("a/b").is_err());
    }

    fn temp_dir(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("branchmint-test-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn save_then_list_round_trip_without_leftover_temp_files() {
        let d = temp_dir("roundtrip");
        write_map(&d, "abc", r#"{"meta":{"id":"abc","title":"One"},"nodes":{}}"#).unwrap();
        write_map(&d, "abc", r#"{"meta":{"id":"abc","title":"Two"},"nodes":{}}"#).unwrap(); // overwrite
        write_map(&d, "def", r#"{"meta":{"id":"def","title":"Other"}}"#).unwrap();
        let mut titles: Vec<String> = read_metas(&d).unwrap().iter().map(|m| m["title"].as_str().unwrap().to_string()).collect();
        titles.sort();
        assert_eq!(titles, ["Other", "Two"]);
        assert!(fs::read_dir(&d).unwrap().flatten().all(|e| e.path().extension().unwrap() == "json"), "temp file left behind");
        fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn invalid_json_and_bad_ids_never_touch_disk() {
        let d = temp_dir("reject");
        assert!(write_map(&d, "abc", "{ not json").is_err());
        assert!(write_map(&d, "../evil", "{}").is_err());
        assert_eq!(fs::read_dir(&d).unwrap().count(), 0);
        fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn corrupt_files_are_skipped_when_listing() {
        let d = temp_dir("corrupt");
        write_map(&d, "good", r#"{"meta":{"id":"good","title":"Fine"}}"#).unwrap();
        fs::write(d.join("bad.json"), "{ truncated").unwrap();
        fs::write(d.join("notes.txt"), "ignore me").unwrap();
        assert_eq!(read_metas(&d).unwrap().len(), 1);
        fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn percent_decoding() {
        assert_eq!(percent_decode("a%20b%2Fc").unwrap(), "a b/c");
        assert_eq!(percent_decode("%E2%9C%93").unwrap(), "✓");
        assert_eq!(percent_decode("plain").unwrap(), "plain");
        assert_eq!(percent_decode("end%2").unwrap(), "end%2");
    }
}
