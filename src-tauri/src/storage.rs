//! On-disk layout.
//!
//! ```text
//! <app-data>/
//!   vault/            <- the folder that is synced with Git
//!     maps/<id>.jsonl   one record per line (see docs/format.md)
//!     assets/<sha256>.<ext>
//!   cache/<id>.json   derived data (thumbnail, search text); never synced
//!   plugin-settings/<plugin-id>.json
//!   plugins/<name>/   user-installed plugins
//! ```
//! Maps written by older versions (`maps/<id>.json`, one JSON document) are still read and
//! are replaced by a `.jsonl` file on the next save. Writes are atomic (temp file + rename).

use std::fs;
use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};

use serde_json::Value;
use tauri::ipc::{InvokeBody, Request, Response};
use tauri::{AppHandle, Manager};

pub type CmdResult<T> = Result<T, String>;

#[derive(Clone)]
pub struct Paths {
    pub root: PathBuf,
}

impl Paths {
    pub fn vault(&self) -> PathBuf {
        self.root.join("vault")
    }
    pub fn maps(&self) -> PathBuf {
        self.vault().join("maps")
    }
    pub fn assets(&self) -> PathBuf {
        self.vault().join("assets")
    }
    pub fn cache(&self) -> PathBuf {
        self.root.join("cache")
    }
    pub fn settings(&self) -> PathBuf {
        self.root.join("plugin-settings")
    }
    pub fn plugins(&self) -> PathBuf {
        self.root.join("plugins")
    }

    /// Create the folders and move a pre-vault `maps/` folder into place (once).
    pub fn ensure(&self) -> CmdResult<()> {
        let old = self.root.join("maps");
        if old.is_dir() && !self.maps().exists() {
            fs::create_dir_all(self.vault()).map_err(|e| e.to_string())?;
            fs::rename(&old, self.maps()).map_err(|e| e.to_string())?;
        }
        for d in [self.maps(), self.assets(), self.cache(), self.settings(), self.plugins()] {
            fs::create_dir_all(d).map_err(|e| e.to_string())?;
        }
        Ok(())
    }
}

pub fn paths(app: &AppHandle) -> CmdResult<Paths> {
    let p = Paths { root: app.path().app_data_dir().map_err(|e| e.to_string())? };
    p.ensure()?;
    Ok(p)
}

/// Ids are generated by the frontend. A safe charset means an id can never escape its folder.
pub fn validate_id(id: &str) -> CmdResult<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if ok { Ok(()) } else { Err(format!("invalid id: {id:?}")) }
}

/// Plugin ids look like `branchmint.sync`.
pub fn validate_plugin_id(id: &str) -> CmdResult<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && !id.starts_with('.')
        && !id.contains("..")
        && id.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'));
    if ok { Ok(()) } else { Err(format!("invalid plugin id: {id:?}")) }
}

/// `<64 hex>.<png|jpg|webp|gif>`
pub fn validate_asset_name(name: &str) -> CmdResult<()> {
    let ok = name.split_once('.').is_some_and(|(h, ext)| {
        h.len() == 64 && h.chars().all(|c| matches!(c, '0'..='9' | 'a'..='f')) && matches!(ext, "png" | "jpg" | "webp" | "gif")
    });
    if ok { Ok(()) } else { Err(format!("invalid asset name: {name:?}")) }
}

pub fn atomic_write(path: &Path, bytes: &[u8]) -> CmdResult<()> {
    let tmp = path.with_extension("tmp");
    {
        let mut f = fs::File::create(&tmp).map_err(|e| e.to_string())?;
        f.write_all(bytes).map_err(|e| e.to_string())?;
        f.sync_all().map_err(|e| e.to_string())?;
    }
    fs::rename(&tmp, path).map_err(|e| e.to_string())
}

/// A map file is valid when every non-empty line is a JSON value (JSONL, or a one-line JSON doc).
fn validate_map_text(text: &str) -> CmdResult<()> {
    let mut lines = 0;
    for (i, line) in text.lines().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        serde_json::from_str::<Value>(line).map_err(|e| format!("refusing to save: line {} is not valid JSON ({e})", i + 1))?;
        lines += 1;
    }
    if lines == 0 { Err("refusing to save an empty map".into()) } else { Ok(()) }
}

// ---------- pure helpers (unit-tested) ----------

fn first_line_json(path: &Path) -> Option<Value> {
    let mut line = String::new();
    BufReader::new(fs::File::open(path).ok()?).read_line(&mut line).ok()?;
    serde_json::from_str(&line).ok()
}

/// Header `meta` of every map in the vault, with cached thumbnail/search text when still fresh.
pub fn read_metas(p: &Paths) -> CmdResult<Vec<Value>> {
    let mut out: Vec<Value> = Vec::new();
    let mut seen = std::collections::HashSet::new();
    let mut entries: Vec<_> = fs::read_dir(p.maps()).map_err(|e| e.to_string())?.flatten().collect();
    entries.sort_by_key(|e| std::cmp::Reverse(e.file_name())); // ".jsonl" sorts after ".json": prefer it
    for entry in entries {
        let path = entry.path();
        let ext = path.extension().and_then(|e| e.to_str()).unwrap_or("");
        let Some(id) = path.file_stem().and_then(|s| s.to_str()).map(str::to_owned) else { continue };
        if !matches!(ext, "json" | "jsonl") || seen.contains(&id) {
            continue;
        }
        let doc = if ext == "jsonl" {
            first_line_json(&path)
        } else {
            fs::read_to_string(&path).ok().and_then(|t| serde_json::from_str(&t).ok())
        };
        let Some(mut meta) = doc.and_then(|mut d| d.get_mut("meta").map(Value::take)) else { continue };
        if !meta.is_object() {
            continue;
        }
        if let Some(cache) = fs::read_to_string(p.cache().join(format!("{id}.json"))).ok().and_then(|t| serde_json::from_str::<Value>(&t).ok()) {
            if cache.get("updatedAt") == meta.get("updatedAt") {
                for k in ["thumb", "search"] {
                    if let Some(v) = cache.get(k) {
                        meta[k] = v.clone();
                    }
                }
            }
        }
        seen.insert(id);
        out.push(meta);
    }
    Ok(out)
}

pub fn load_map_text(p: &Paths, id: &str) -> CmdResult<Option<String>> {
    validate_id(id)?;
    for ext in ["jsonl", "json"] {
        let path = p.maps().join(format!("{id}.{ext}"));
        if path.exists() {
            return fs::read_to_string(path).map(Some).map_err(|e| e.to_string());
        }
    }
    Ok(None)
}

pub fn write_map(p: &Paths, id: &str, text: &str) -> CmdResult<()> {
    validate_id(id)?;
    validate_map_text(text)?;
    atomic_write(&p.maps().join(format!("{id}.jsonl")), text.as_bytes())?;
    let legacy = p.maps().join(format!("{id}.json"));
    if legacy.exists() {
        let _ = fs::remove_file(legacy);
    }
    Ok(())
}

pub fn remove_map(p: &Paths, id: &str) -> CmdResult<()> {
    validate_id(id)?;
    for path in [p.maps().join(format!("{id}.jsonl")), p.maps().join(format!("{id}.json")), p.cache().join(format!("{id}.json"))] {
        if path.exists() {
            fs::remove_file(path).map_err(|e| e.to_string())?;
        }
    }
    Ok(())
}

// ---------- commands ----------

#[tauri::command]
pub fn list_maps(app: AppHandle) -> CmdResult<Vec<Value>> {
    read_metas(&paths(&app)?)
}

#[tauri::command]
pub fn load_map(app: AppHandle, id: String) -> CmdResult<Option<String>> {
    load_map_text(&paths(&app)?, &id)
}

#[tauri::command]
pub fn save_map(app: AppHandle, id: String, text: String) -> CmdResult<()> {
    write_map(&paths(&app)?, &id, &text)
}

#[tauri::command]
pub fn delete_map(app: AppHandle, id: String) -> CmdResult<()> {
    remove_map(&paths(&app)?, &id)
}

#[tauri::command]
pub fn save_cache(app: AppHandle, id: String, json: String) -> CmdResult<()> {
    validate_id(&id)?;
    serde_json::from_str::<Value>(&json).map_err(|e| e.to_string())?;
    atomic_write(&paths(&app)?.cache().join(format!("{id}.json")), json.as_bytes())
}

#[tauri::command]
pub fn asset_exists(app: AppHandle, name: String) -> CmdResult<bool> {
    validate_asset_name(&name)?;
    Ok(paths(&app)?.assets().join(name).exists())
}

/// Raw body = file bytes, `name` header = asset name.
#[tauri::command]
pub fn save_asset(app: AppHandle, request: Request<'_>) -> CmdResult<()> {
    let InvokeBody::Raw(bytes) = request.body() else { return Err("expected a raw body".into()) };
    let name = request.headers().get("name").and_then(|v| v.to_str().ok()).ok_or("missing name header")?;
    validate_asset_name(name)?;
    let path = paths(&app)?.assets().join(name);
    if path.exists() {
        return Ok(()); // content-addressed: same name means same bytes
    }
    atomic_write(&path, bytes)
}

#[tauri::command]
pub fn load_asset(app: AppHandle, name: String) -> CmdResult<Response> {
    validate_asset_name(&name)?;
    fs::read(paths(&app)?.assets().join(name)).map(Response::new).map_err(|e| e.to_string())
}

/// Writes raw bytes (PNG/PDF/...) to a path chosen in the save dialog. The path comes in the
/// `path` header (URI-encoded) so big binaries are not serialised as JSON number arrays.
#[tauri::command]
pub fn save_bytes(request: Request<'_>) -> CmdResult<()> {
    let InvokeBody::Raw(bytes) = request.body() else { return Err("expected a raw body".into()) };
    let encoded = request.headers().get("path").and_then(|v| v.to_str().ok()).ok_or("missing path header")?;
    atomic_write(Path::new(&percent_decode(encoded)?), bytes)
}

pub fn percent_decode(s: &str) -> CmdResult<String> {
    let b = s.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            let hex = std::str::from_utf8(&b[i + 1..i + 3]).map_err(|e| e.to_string())?;
            out.push(u8::from_str_radix(hex, 16).map_err(|e| e.to_string())?);
            i += 3;
        } else {
            out.push(b[i]);
            i += 1;
        }
    }
    String::from_utf8(out).map_err(|e| e.to_string())
}

#[tauri::command]
pub fn plugin_settings_get(app: AppHandle, id: String) -> CmdResult<Option<String>> {
    validate_plugin_id(&id)?;
    let path = paths(&app)?.settings().join(format!("{id}.json"));
    if path.exists() { fs::read_to_string(path).map(Some).map_err(|e| e.to_string()) } else { Ok(None) }
}

#[tauri::command]
pub fn plugin_settings_set(app: AppHandle, id: String, json: String) -> CmdResult<()> {
    validate_plugin_id(&id)?;
    serde_json::from_str::<Value>(&json).map_err(|e| e.to_string())?;
    atomic_write(&paths(&app)?.settings().join(format!("{id}.json")), json.as_bytes())
}

#[tauri::command]
pub fn vault_path(app: AppHandle) -> CmdResult<String> {
    Ok(paths(&app)?.vault().to_string_lossy().into_owned())
}

#[tauri::command]
pub fn device_name() -> String {
    for var in ["HOSTNAME", "COMPUTERNAME"] {
        if let Ok(v) = std::env::var(var) {
            if !v.trim().is_empty() {
                return v.trim().to_string();
            }
        }
    }
    std::process::Command::new("hostname")
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "this device".into())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_paths(name: &str) -> Paths {
        let root = std::env::temp_dir().join(format!("branchmint-test-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        let p = Paths { root };
        p.ensure().unwrap();
        p
    }
    const MAP: &str = "{\"t\":\"map\",\"meta\":{\"id\":\"abc\",\"title\":\"One\",\"updatedAt\":5}}\n{\"t\":\"node\",\"id\":\"n1\"}\n";

    #[test]
    fn ids_assets_and_plugin_ids_are_validated() {
        assert!(validate_id("abc-123_X").is_ok());
        for bad in ["../etc/passwd", "", "a/b", "a.b"] {
            assert!(validate_id(bad).is_err(), "{bad}");
        }
        assert!(validate_plugin_id("branchmint.sync").is_ok());
        for bad in [".hidden", "a..b", "a/b", ""] {
            assert!(validate_plugin_id(bad).is_err(), "{bad}");
        }
        let hash = "a".repeat(64);
        assert!(validate_asset_name(&format!("{hash}.png")).is_ok());
        assert!(validate_asset_name(&format!("{hash}.exe")).is_err());
        assert!(validate_asset_name("../x.png").is_err());
        assert!(validate_asset_name(&format!("{}.png", "A".repeat(64))).is_err());
    }

    #[test]
    fn save_load_list_round_trip_leaves_no_temp_files() {
        let p = temp_paths("roundtrip");
        write_map(&p, "abc", MAP).unwrap();
        write_map(&p, "abc", &MAP.replace("One", "Two")).unwrap();
        let metas = read_metas(&p).unwrap();
        assert_eq!(metas.len(), 1);
        assert_eq!(metas[0]["title"], "Two");
        assert!(load_map_text(&p, "abc").unwrap().unwrap().contains("Two"));
        assert!(load_map_text(&p, "missing").unwrap().is_none());
        assert!(fs::read_dir(p.maps()).unwrap().flatten().all(|e| e.path().extension().unwrap() == "jsonl"));
        fs::remove_dir_all(&p.root).unwrap();
    }

    #[test]
    fn bad_input_never_touches_disk() {
        let p = temp_paths("reject");
        assert!(write_map(&p, "abc", "{ not json").is_err());
        assert!(write_map(&p, "abc", "  \n").is_err());
        assert!(write_map(&p, "../evil", MAP).is_err());
        assert_eq!(fs::read_dir(p.maps()).unwrap().count(), 0);
        fs::remove_dir_all(&p.root).unwrap();
    }

    #[test]
    fn legacy_json_is_listed_and_replaced_on_save() {
        let p = temp_paths("legacy");
        fs::write(p.maps().join("old.json"), r#"{"v":1,"meta":{"id":"old","title":"Legacy","updatedAt":1},"nodes":{}}"#).unwrap();
        assert_eq!(read_metas(&p).unwrap()[0]["title"], "Legacy");
        assert!(load_map_text(&p, "old").unwrap().unwrap().contains("Legacy"));
        write_map(&p, "old", &MAP.replace("abc", "old")).unwrap();
        assert!(!p.maps().join("old.json").exists());
        assert_eq!(read_metas(&p).unwrap().len(), 1);
        fs::remove_dir_all(&p.root).unwrap();
    }

    #[test]
    fn cache_is_used_only_while_fresh() {
        let p = temp_paths("cache");
        write_map(&p, "abc", MAP).unwrap();
        fs::write(p.cache().join("abc.json"), r#"{"updatedAt":5,"thumb":"<svg/>","search":"one"}"#).unwrap();
        assert_eq!(read_metas(&p).unwrap()[0]["thumb"], "<svg/>");
        fs::write(p.cache().join("abc.json"), r#"{"updatedAt":4,"thumb":"<svg/>"}"#).unwrap(); // stale
        assert!(read_metas(&p).unwrap()[0].get("thumb").is_none());
        fs::remove_dir_all(&p.root).unwrap();
    }

    #[test]
    fn corrupt_and_foreign_files_are_skipped() {
        let p = temp_paths("corrupt");
        write_map(&p, "good", &MAP.replace("abc", "good")).unwrap();
        fs::write(p.maps().join("bad.jsonl"), "{ truncated").unwrap();
        fs::write(p.maps().join("notes.txt"), "ignore me").unwrap();
        assert_eq!(read_metas(&p).unwrap().len(), 1);
        fs::remove_dir_all(&p.root).unwrap();
    }

    #[test]
    fn old_maps_folder_moves_into_the_vault() {
        let root = std::env::temp_dir().join(format!("branchmint-test-migrate-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(root.join("maps")).unwrap();
        fs::write(root.join("maps/a.json"), r#"{"meta":{"id":"a","title":"A","updatedAt":1}}"#).unwrap();
        let p = Paths { root: root.clone() };
        p.ensure().unwrap();
        assert!(!root.join("maps").exists());
        assert_eq!(read_metas(&p).unwrap().len(), 1);
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn percent_decoding() {
        assert_eq!(percent_decode("a%20b%2Fc").unwrap(), "a b/c");
        assert_eq!(percent_decode("%E2%9C%93").unwrap(), "✓");
        assert_eq!(percent_decode("end%2").unwrap(), "end%2");
    }
}
